#!/usr/bin/env node
/**
 * Build the committed bundles (ARCHITECTURE §12).
 *
 * One file per entry point, unminified, so a committed bundle can be read and
 * diffed. The CI drift gate re-runs this and fails if `dist/` moves, which only
 * works because esbuild is exact-pinned and the lockfile is committed.
 */
import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const ENTRIES = [
  { in: 'src/hooks/session-start.ts', out: 'session-start' },
  { in: 'src/hooks/session-end.ts', out: 'session-end' },
  { in: 'src/worker/main.ts', out: 'worker' },
  { in: 'src/commands/cli.ts', out: 'cli' },
];

/**
 * `tar` reaches for `require` in a couple of places. Defining it from
 * `import.meta.url` is cheap insurance for any CJS that gets bundled in.
 */
const BANNER = `import { createRequire as __archiveCreateRequire } from 'node:module';
const require = __archiveCreateRequire(import.meta.url);`;

async function checkVersion() {
  const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const source = await readFile(path.join(root, 'src/version.ts'), 'utf8');
  const match = /ARCHIVER_VERSION = '([^']+)'/.exec(source);
  if (match?.[1] !== pkg.version) {
    throw new Error(
      `src/version.ts says ${match?.[1] ?? 'nothing'} but package.json says ${pkg.version}`,
    );
  }
  return pkg.version;
}

async function main() {
  const version = await checkVersion();
  const outdir = path.join(root, 'dist');
  await rm(outdir, { recursive: true, force: true });
  await mkdir(outdir, { recursive: true });

  for (const entry of ENTRIES) {
    await build({
      entryPoints: [path.join(root, entry.in)],
      outfile: path.join(outdir, `${entry.out}.mjs`),
      // Paths esbuild writes into comments are relative to this, so without it
      // the committed bundles differ by where `npm run build` was run from and
      // the CI drift gate fails for no reason.
      absWorkingDir: root,
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node22',
      // Never minified: a committed artifact has to be reviewable.
      minify: false,
      sourcemap: false,
      // 'eof' keeps any licence banner a dependency puts in its own source.
      // The notices file below covers the packages that do not.
      legalComments: 'eof',
      banner: { js: BANNER },
      logLevel: 'warning',
    });
  }

  const notices = await writeThirdPartyNotices();

  const built = (await readdir(outdir)).sort();
  console.log(`built ${built.length} bundles for ${version}: ${built.join(', ')}`);
  console.log(`third-party notices: ${notices} package(s)`);
}

/**
 * Collect the licence text of every package whose code ends up inside the
 * bundles.
 *
 * esbuild inlines those packages, so the notices have to travel with the
 * repository or the redistribution breaks the terms they were given under.
 * Generated at build time so it cannot drift from what is actually bundled.
 */
async function writeThirdPartyNotices() {
  const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'));
  const entries = Object.entries(lock.packages ?? {})
    .filter(([name, meta]) => name.startsWith('node_modules/') && meta.dev !== true)
    .sort(([a], [b]) => (a < b ? -1 : 1));

  const sections = [];
  for (const [dir, meta] of entries) {
    const name = dir.replace(/^node_modules\//, '');
    sections.push({
      name,
      version: meta.version ?? '',
      license: meta.license ?? 'see text below',
      text: await readLicenseText(path.join(root, dir)),
    });
  }

  const body = [
    '# Third-party notices',
    '',
    'The bundles in `dist/` inline the packages below. Their licences are',
    'reproduced here because the code travels with this repository.',
    '',
    'Regenerated by `npm run build`; do not edit by hand.',
    '',
    ...sections.flatMap((section) => [
      `## ${section.name} ${section.version}`,
      '',
      `License: ${section.license}`,
      '',
      '```',
      section.text.trimEnd(),
      '```',
      '',
    ]),
  ].join('\n');

  await writeFile(path.join(root, 'THIRD-PARTY-NOTICES.md'), body);
  return sections.length;
}

async function readLicenseText(packageDir) {
  for (const candidate of ['LICENSE', 'LICENSE.md', 'LICENCE', 'LICENSE.txt']) {
    try {
      return await readFile(path.join(packageDir, candidate), 'utf8');
    } catch {
      // Try the next spelling.
    }
  }
  throw new Error(`no licence file found in ${packageDir}`);
}

await main();
